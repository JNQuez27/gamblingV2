// One-off generator: splits the three Freepik onboarding SVGs into their
// top-level layer groups so each layer can be animated independently in
// splash.tsx. Each emitted layer is a standalone <svg> (full 0 0 500 500
// viewBox + shared <defs>) that draws only one group, so stacking the layers
// absolutely reconstructs the full illustration.
//
// Run:  node scripts/gen-onboarding-art.js
const fs = require('fs');
const path = require('path');

const IMG_DIR = 'C:/Users/Quezada/Documents/CodeX/images';
const OUT = path.join(__dirname, '..', 'constants', 'onboardingArt.ts');

// key -> source file. key is what splash.tsx references.
const SOURCES = {
  book: 'Book lover-bro.svg',       // "Know your pattern"
  time: 'Time management-bro.svg',  // "Set your limits"
  features: 'Features Overview-pana.svg', // "Grow your control"
};

function extractViewBox(svg) {
  const m = svg.match(/<svg[^>]*viewBox="([^"]+)"/i);
  return m ? m[1] : '0 0 500 500';
}

function extractDefs(svg) {
  const m = svg.match(/<defs>[\s\S]*?<\/defs>/i);
  return m ? m[0] : '';
}

// Returns the top-level <g ...>...</g> blocks inside `body` (handles nesting).
function topLevelGroups(body) {
  const groups = [];
  let i = 0;
  while (i < body.length) {
    const gStart = body.indexOf('<g', i);
    if (gStart === -1) break;
    const openEnd = body.indexOf('>', gStart) + 1;
    let depth = 1;
    let j = openEnd;
    while (depth > 0 && j < body.length) {
      const nextOpen = body.indexOf('<g', j);
      const nextClose = body.indexOf('</g>', j);
      if (nextClose === -1) { j = body.length; break; }
      if (nextOpen !== -1 && nextOpen < nextClose) {
        depth++;
        j = nextOpen + 2;
      } else {
        depth--;
        j = nextClose + 4;
      }
    }
    groups.push(body.slice(gStart, j));
    i = j;
  }
  return groups;
}

function groupId(group) {
  const m = group.match(/<g id="freepik--([^"-]+(?:-[^"-]+)*?)--inject/i);
  return m ? m[1] : 'layer';
}

function build(key, file) {
  const svg = fs.readFileSync(path.join(IMG_DIR, file), 'utf8');
  const viewBox = extractViewBox(svg);
  const defs = extractDefs(svg);
  // Body = everything after the </defs> (or after the opening <svg> if no defs)
  // up to the final </svg>.
  const afterDefs = defs ? svg.slice(svg.indexOf(defs) + defs.length) : svg.slice(svg.indexOf('>') + 1);
  const body = afterDefs.slice(0, afterDefs.lastIndexOf('</svg>'));
  const groups = topLevelGroups(body);

  const layers = groups.map((g) => {
    const xml =
      `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="${viewBox}">` +
      defs +
      g +
      `</svg>`;
    return { id: groupId(g), xml };
  });

  return { key, viewBox, layers };
}

const arts = Object.entries(SOURCES).map(([key, file]) => build(key, file));

let out = `// AUTO-GENERATED by scripts/gen-onboarding-art.js - do not edit by hand.\n`;
out += `// Each illustration is split into its top-level layer groups so splash.tsx\n`;
out += `// can animate them independently. Regenerate with:\n`;
out += `//   node scripts/gen-onboarding-art.js\n\n`;
out += `export interface ArtLayer { id: string; xml: string; }\n`;
out += `export interface Art { viewBox: string; layers: ArtLayer[]; }\n\n`;
out += `export type ArtKey = ${Object.keys(SOURCES).map((k) => `'${k}'`).join(' | ')};\n\n`;
out += `export const ONBOARDING_ART: Record<ArtKey, Art> = {\n`;
for (const art of arts) {
  out += `  ${art.key}: {\n`;
  out += `    viewBox: ${JSON.stringify(art.viewBox)},\n`;
  out += `    layers: [\n`;
  for (const layer of art.layers) {
    out += `      { id: ${JSON.stringify(layer.id)}, xml: ${JSON.stringify(layer.xml)} },\n`;
  }
  out += `    ],\n`;
  out += `  },\n`;
}
out += `};\n`;

fs.writeFileSync(OUT, out, 'utf8');
console.log('Wrote', OUT);
for (const art of arts) {
  console.log(`  ${art.key}: ${art.layers.length} layers -> ${art.layers.map((l) => l.id).join(', ')}`);
}
